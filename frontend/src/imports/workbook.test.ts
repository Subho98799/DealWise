import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { countDataRows, isSupportedImportFile, openImportWorkbook, readImportSheet, summarizeImportWorkbook } from './workbook'

async function fixture(name: string): Promise<ArrayBuffer> {
  const bytes = await readFile(resolve(process.cwd(), 'src', 'imports', 'fixtures', name))
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer
}

describe('browser spreadsheet parsing helpers', () => {
  it('reads a generated messy workbook with a title, merged cells, blank row, mixed dates and duplicates', async () => {
    const workbook = openImportWorkbook(await fixture('messy-deals.xlsx'))
    const summary = summarizeImportWorkbook(workbook)
    expect(summary[0].rows[0][0]).toBe('Deal history export')
    expect(summary[0].rows[1][0]).toBe('Item name')
    const rows = readImportSheet(workbook, 'Deals')
    expect(countDataRows(rows, 1)).toBe(3)
    expect(rows[2][5]).toBe('₹1,299.50')
    expect(rows[4][4]).toBe('08/11/2025')
    expect(rows[5][4]).toBe('November 8, 2025')
    expect(rows[5][9]).toBe('mystery')
  })

  it('parses legacy XLS and CSV generated by the fixture script', async () => {
    for (const filename of ['messy-deals.xls', 'messy-deals.csv']) {
      const workbook = openImportWorkbook(await fixture(filename))
      expect(workbook.SheetNames.length).toBeGreaterThan(0)
      expect(readImportSheet(workbook, workbook.SheetNames[0])[1][0]).toBe('Item name')
    }
    expect(isSupportedImportFile('deals.XLS')).toBe(true)
    expect(isSupportedImportFile('deals.txt')).toBe(false)
  })
})
